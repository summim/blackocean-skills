"""화염 주먹 메시 생성기.
SDF(거리장)로 매끈한 주먹 모양을 정의하고 마칭 큐브로 삼각형 메시를 뽑는다.
좌표계: +Z = 주먹이 날아가는 앞쪽, +Y = 위, X = 좌우. 1 단위 = 마인크래프트 1블록.
출력: OBJ(모드 내장 렌더러용, 법선·UV 포함) + GLB(Photon/Blender용)
"""
import sys, os
import numpy as np
import trimesh
from skimage import measure

OUT = sys.argv[1]


def sd_sphere(p, c, r):
    return np.linalg.norm(p - c, axis=-1) - r


def sd_capsule(p, a, b, ra, rb=None):
    rb = ra if rb is None else rb
    a = np.asarray(a, float); b = np.asarray(b, float)
    pa = p - a; ba = b - a
    h = np.clip((pa @ ba) / (ba @ ba), 0, 1)
    r = ra + (rb - ra) * h
    return np.linalg.norm(pa - h[..., None] * ba, axis=-1) - r


def sd_round_box(p, c, half, r):
    q = np.abs(p - c) - (np.asarray(half) - r)
    return np.linalg.norm(np.maximum(q, 0), axis=-1) + np.minimum(q.max(-1), 0) - r


def smin(a, b, k):
    h = np.clip(0.5 + 0.5 * (b - a) / k, 0, 1)
    return b * (1 - h) + a * h - k * h * (1 - h)


def fist_sdf(p):
    d = sd_round_box(p, np.array([0.0, 0.0, 0.0]), [0.56, 0.44, 0.42], 0.24)
    # 손가락 4개: 앞에서 보이는 첫째 마디 + 아래로 말려 들어가는 둘째 마디 + 툭 튀어나온 관절
    xs = [-0.42, -0.14, 0.14, 0.40]
    rs = [0.135, 0.15, 0.15, 0.14]
    for x, r in zip(xs, rs):
        knuckle = sd_sphere(p, np.array([x, 0.24, 0.34]), r + 0.03)
        seg1 = sd_capsule(p, [x, 0.22, 0.40], [x, -0.16, 0.50], r)
        seg2 = sd_capsule(p, [x, -0.16, 0.50], [x, -0.30, 0.16], r * 0.92)
        f = smin(smin(knuckle, seg1, 0.06), seg2, 0.06)
        d = smin(d, f, 0.07)
    # 엄지: 손 옆에서 앞으로 감아 손가락 둘째 마디를 덮음
    thumb_base = sd_sphere(p, np.array([0.58, -0.04, 0.02]), 0.22)
    thumb = sd_capsule(p, [0.60, -0.08, 0.06], [0.12, -0.30, 0.52], 0.14, 0.12)
    d = smin(d, smin(thumb_base, thumb, 0.1), 0.1)
    # 손목 → 뒤로 갈수록 가늘어짐
    wrist = sd_capsule(p, [0.0, -0.02, -0.25], [0.0, -0.02, -1.05], 0.40, 0.26)
    d = smin(d, wrist, 0.22)
    return d


def shell_sdf(p):
    """겉불꽃: 본체를 부풀리고 뒤로 휘는 불꽃 혀 5갈래를 붙인다."""
    d = fist_sdf(p) - 0.09
    tongues = [
        ([0.00, 0.30, -0.6], [0.05, 0.55, -2.0], 0.30),
        ([-0.30, 0.05, -0.6], [-0.55, 0.10, -1.8], 0.24),
        ([0.32, 0.02, -0.6], [0.60, -0.05, -1.75], 0.24),
        ([0.05, -0.30, -0.6], [0.10, -0.50, -1.6], 0.22),
        ([0.00, 0.00, -0.8], [0.00, 0.05, -2.25], 0.26),
    ]
    for a, b, r in tongues:
        # 뒤로 갈수록 가늘어지는 곡선 혀 (가운데 지점을 살짝 띄워 휘게)
        a = np.array(a); b = np.array(b)
        m = (a + b) / 2 + np.array([0.0, 0.12, 0.0])
        t = smin(sd_capsule(p, a, m, r, r * 0.7), sd_capsule(p, m, b, r * 0.7, 0.02), 0.08)
        d = smin(d, t, 0.18)
    return d


def build(sdf, lo, hi, step):
    xs = np.arange(lo[0], hi[0], step)
    ys = np.arange(lo[1], hi[1], step)
    zs = np.arange(lo[2], hi[2], step)
    X, Y, Z = np.meshgrid(xs, ys, zs, indexing='ij')
    P = np.stack([X, Y, Z], -1)
    vol = sdf(P)
    verts, faces, _, _ = measure.marching_cubes(vol, 0.0, spacing=(step, step, step))
    verts += np.array(lo)
    m = trimesh.Trimesh(verts, faces, process=True)
    if m.volume < 0:
        m.invert()  # 바깥을 향하게 (반시계 방향 = 앞면)
    trimesh.smoothing.filter_taubin(m, iterations=10)
    return m


def decimate(m, target):
    if len(m.faces) <= target:
        return m
    return m.simplify_quadric_decimation(face_count=target)


def planar_uv(v):
    # 이음새 없는 평면 투영 UV. v 좌표가 앞→뒤 방향이라 셰이더에서 v를 흘리면 불이 뒤로 흐른다.
    u = v[:, 0] * 0.55 + v[:, 1] * 0.30
    w = -v[:, 2] * 0.45 + v[:, 1] * 0.15
    return np.stack([u, w], -1)


def write_obj(m, path, name):
    v = m.vertices; n = m.vertex_normals; uv = planar_uv(v)
    with open(path, 'w') as f:
        f.write(f'# {name} - generated by make_meshes.py ({len(m.faces)} triangles)\n')
        f.write('# +Z forward, +Y up, 1 unit = 1 block\n')
        for p in v: f.write(f'v {p[0]:.4f} {p[1]:.4f} {p[2]:.4f}\n')
        for t in uv: f.write(f'vt {t[0]:.4f} {t[1]:.4f}\n')
        for q in n: f.write(f'vn {q[0]:.4f} {q[1]:.4f} {q[2]:.4f}\n')
        for a, b, c in m.faces + 1:
            f.write(f'f {a}/{a}/{a} {b}/{b}/{b} {c}/{c}/{c}\n')


def export_glb(m, path):
    mm = m.copy()
    mm.visual = trimesh.visual.TextureVisuals(uv=planar_uv(mm.vertices))
    mm.export(path)


os.makedirs(OUT + '/obj', exist_ok=True)
os.makedirs(OUT + '/glb', exist_ok=True)

core = decimate(build(fist_sdf, (-1.0, -0.8, -1.4), (1.0, 0.8, 0.9), 0.03), 2000)
shell = decimate(build(shell_sdf, (-1.0, -0.9, -2.5), (1.1, 1.0, 1.0), 0.035), 1500)
for name, m in [('fist_core', core), ('fist_shell', shell)]:
    write_obj(m, f'{OUT}/obj/{name}.obj', name)
    export_glb(m, f'{OUT}/glb/{name}.glb')
    print(name, 'tris', len(m.faces), 'bounds', np.round(m.bounds, 2).tolist())

# 보조 메시 (모드는 코드로 직접 그리지만 Photon/Blender용으로 같이 내보냄)
ring = trimesh.creation.annulus(r_min=0.7, r_max=1.0, height=0.04, sections=64)
shock = trimesh.creation.annulus(r_min=0.92, r_max=1.0, height=0.01, sections=96)
sphere = trimesh.creation.uv_sphere(radius=1.0, count=[24, 32])
spark = trimesh.creation.cone(radius=0.08, height=1.0, sections=6)
for name, m in [('ring_band', ring), ('shock_ring', shock), ('blast_sphere', sphere), ('spark_streak', spark)]:
    m.export(f'{OUT}/glb/{name}.glb')
    print(name, 'tris', len(m.faces))
